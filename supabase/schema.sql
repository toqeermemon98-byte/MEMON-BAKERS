-- MEMON BAKERS Supabase schema
-- Run this whole file once in Supabase Dashboard > SQL Editor.
-- Keep Row Level Security enabled. The Express API accesses these tables using
-- SUPABASE_SERVICE_ROLE_KEY on the server only. Never put that key in VITE_* vars.

create table if not exists public.app_users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  password_hash text not null,
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price integer not null check (price > 0),
  image text not null,
  description text not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.app_users(id),
  customer_name text not null,
  email text not null,
  phone text not null,
  address text not null,
  notes text,
  total integer not null check (total >= 0),
  status text not null default 'Pending',
  payment_method text not null,
  payment_status text not null default 'Unpaid',
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint not null,
  name text not null,
  price integer not null check (price > 0),
  quantity integer not null check (quantity > 0)
);

alter table public.app_users enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- No public/anon policies are created. All database access is performed by
-- the protected Express API using the server-only service role key.
